"""Writes src/shared/ModelBlueprints.luau from blueprints.json.

Neighbouring blocks of the same colour are merged into as few boxes as possible (greedy meshing),
so a dino becomes a few dozen Parts instead of hundreds. Each entry is
{x, y, z, sizeX, sizeY, sizeZ, colourIndex} in blocks, with x forward, y across, z up (Luau
turns those into Roblox axes).
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE.parent.parent / "src" / "shared" / "ModelBlueprints.luau"


def greedy(cells):
    remaining = dict(cells)
    boxes = []
    for key in sorted(cells, key=lambda k: (k[2], k[1], k[0])):
        if key not in remaining:
            continue
        colour = remaining[key]
        x0, y0, z0 = key

        def free(x, y, z):
            return remaining.get((x, y, z)) == colour

        x1 = x0
        while free(x1 + 1, y0, z0):
            x1 += 1
        y1 = y0
        while all(free(x, y1 + 1, z0) for x in range(x0, x1 + 1)):
            y1 += 1
        z1 = z0
        while all(free(x, y, z1 + 1) for x in range(x0, x1 + 1) for y in range(y0, y1 + 1)):
            z1 += 1
        for x in range(x0, x1 + 1):
            for y in range(y0, y1 + 1):
                for z in range(z0, z1 + 1):
                    del remaining[(x, y, z)]
        boxes.append((x0, y0, z0, x1 - x0 + 1, y1 - y0 + 1, z1 - z0 + 1, colour))
    return boxes


def main():
    data = json.loads((HERE / "blueprints.json").read_text())
    palette = []
    index = {}
    lines = []
    total = 0
    for name, blocks in data.items():
        cells = {(x, y, z): c for x, y, z, c in blocks}
        boxes = greedy(cells)
        total += len(boxes)
        entries = []
        for x, y, z, sx, sy, sz, colour in boxes:
            if colour not in index:
                index[colour] = len(palette) + 1
                palette.append(colour)
            entries.append(f"{{{x},{y},{z},{sx},{sy},{sz},{index[colour]}}}")
        lines.append(f'\t{name} = {{{",".join(entries)}}},')
        print(f"{name}: {len(blocks)} blocks -> {len(boxes)} boxes")
    colours = ", ".join(f'"{c}"' for c in palette)
    OUT.write_text(
        "-- Generated by assets/models/export_luau.py from blueprints.json; don't edit by hand.\n"
        "-- Block models for dinos, eggs, biome islands and shop art, as merged boxes:\n"
        "-- {x, y, z, sizeX, sizeY, sizeZ, colourIndex} in blocks (x forward, y across, z up).\n"
        "return {\n"
        f"\tpalette = {{ {colours} }},\n"
        "\tmodels = {\n"
        + "\n".join("\t" + line for line in lines)
        + "\n\t},\n}\n"
    )
    print("total boxes:", total, "->", OUT, OUT.stat().st_size // 1024, "KB")


main()
